#include "../header/ft_push_swap.h"

void	ft_free_2point(char ***str)
{
	char	**tmp;
	int		i;

	tmp = **str;
	i = 0;
	while (tmp[i])
	{
		free(tmp[i]);
		i++;
	}
	free(tmp);
	**tmp = NULL;
}
